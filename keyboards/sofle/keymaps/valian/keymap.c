/* ====================================================================
 * ENCODERS
 *   _BASE  : volume (both encoders).
 *   _LOWER : page scroll (PgUp/PgDn).
 *   _RAISE : switch tab/track (Ctrl+Tab / Ctrl+Shift+Tab).
 * ==================================================================== */
#ifdef ENCODER_ENABLE
bool encoder_update_user(uint8_t index, bool clockwise) {
    switch (get_highest_layer(layer_state)) {
        case _LOWER:
            if (clockwise) { tap_code(KC_PGDN); } else { tap_code(KC_PGUP); }
            break;
        case _RAISE:
            if (clockwise) {
                tap_code16(C(KC_TAB));         // next tab/track
            } else {
                tap_code16(C(S(KC_TAB)));      // previous tab/track
            }
            break;
        case _BASE:
        default:
            if (clockwise) { tap_code(KC_VOLU); } else { tap_code(KC_VOLD); }
            break;
    }
    return false;
}
#endif

/* ====================================================================
 * PER-LAYER RGB (rgblight, underglow)
 *   _BASE  : dynamic hue controlled by HUI/HUD.
 *   _LOWER : red.
 *   _RAISE : green.
 *   _NUMPAD: blue.
 *   Caps Lock on: gold, takes priority.
 * ==================================================================== */
uint8_t current_hue;
uint8_t current_val;

void keyboard_post_init_user(void) {
    current_hue = rgblight_get_hue();
    current_val = RGBLIGHT_LIMIT_VAL;
}

layer_state_t layer_state_set_user(layer_state_t state) {
    if (host_keyboard_led_state().caps_lock) {
        rgblight_sethsv_noeeprom(HSV_GOLD);
        return state;
    }
    switch (get_highest_layer(state)) {
        case _NUMPAD:
            rgblight_sethsv_noeeprom(HSV_BLUE);
            break;
        case _RAISE:
            rgblight_sethsv_noeeprom(HSV_GREEN);
            break;
        case _LOWER:
            rgblight_sethsv_noeeprom(HSV_RED);
            break;
        case _BASE:
        default:
            rgblight_sethsv_noeeprom(current_hue, 255, current_val);
            break;
    }
    return state;
}

