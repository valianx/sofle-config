static void render_layer(void) {
    switch (get_highest_layer(layer_state)) {
        case _NUMPAD: oled_write_P(PSTR("NUMPD"), false); break;
        case _RAISE:  oled_write_P(PSTR("RAISE"), false); break;
        case _LOWER:  oled_write_P(PSTR("LOWER"), false); break;
        default:      oled_write_P(PSTR("BASE "), false); break;
    }
}

static void render_hsv(void) {
    uint8_t hue_value = rgblight_get_hue();
    uint8_t sat_value = rgblight_get_sat();
    uint8_t val_value = rgblight_get_val();

    oled_write("H ", false);
    hue_str[3] = '\0';
    hue_str[2] = '0' + hue_value % 10;
    hue_str[1] = '0' + (hue_value /= 10) % 10;
    hue_str[0] = '0' + hue_value / 10;
    oled_write(hue_str, false);

    oled_write("S ", false);
    sat_str[3] = '\0';
    sat_str[2] = '0' + sat_value % 10;
    sat_str[1] = '0' + (sat_value /= 10) % 10;
    sat_str[0] = '0' + sat_value / 10;
    oled_write(sat_str, false);

    oled_write("V ", false);
    val_str[3] = '\0';
    val_str[2] = '0' + val_value % 10;
    val_str[1] = '0' + (val_value /= 10) % 10;
    val_str[0] = '0' + val_value / 10;
    oled_write(val_str, false);
}

