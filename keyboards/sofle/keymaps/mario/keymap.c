/* ====================================================================
 * PROCESS RECORD — custom keycodes + estado de animaciones del perro
 * ==================================================================== */
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case HUI:
            if (record->event.pressed) {
                current_hue += 5;  // wrap automatico de uint8_t
                rgblight_sethsv_noeeprom(current_hue, 255, current_val);
            }
            return false;

        case HUD:
            if (record->event.pressed) {
                current_hue -= 5;  // wrap automatico de uint8_t
                rgblight_sethsv_noeeprom(current_hue, 255, current_val);
            }
            return false;

        case LOWER:
            if (record->event.pressed) {
                layer_on(_LOWER);
            } else {
                layer_off(_LOWER);
            }
            update_tri_layer(_LOWER, _RAISE, _NUMPAD);
            return false;

        case RAISE:
            if (record->event.pressed) {
                layer_on(_RAISE);
            } else {
                layer_off(_RAISE);
            }
            update_tri_layer(_LOWER, _RAISE, _NUMPAD);
            return false;

#ifdef OLED_ENABLE
        case KC_LCTL:
        case KC_RCTL:
            isSneaking = record->event.pressed;
            break;
        case KC_LGUI:
            isWalking = record->event.pressed;
            break;
        case KC_RALT:
            isRunning = record->event.pressed;
            break;
        case KC_SPC:
            if (record->event.pressed) {
                isJumping  = true;
                showedJump = false;
            } else {
                isJumping = false;
            }
            break;
#endif
    }
    return true;
}
